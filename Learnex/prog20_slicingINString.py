#In Python, you can extract parts (substrings) of a string using slicing syntax:
#string[start:end:step]
#start → index where the slice begins (inclusive)
#end → index where the slice stops (exclusive)
#step → how many characters to skip each time (default = 1)

a="Mohammad Ayaan Khan"
print(a[0:4])
print(a[:5])
print(a[4:])
print(a[-9:0])
print(a[-12:])